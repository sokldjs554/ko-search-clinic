# 프롬프트 변형 이름 → 시스템 프롬프트. CLI가 이 이름으로 실험을 고른다.
PROMPT_VARIANTS = {
    "full": SYSTEM_PROMPT,  # 도메인 지식을 프롬프트에 박은 것 (기본)
    "minimal": MINIMAL_SYSTEM_PROMPT,  # 지식을 덜어낸 것
}


def build_brief(query: str, n_results: int, knowledge: str = "") -> str:
    """진료 브리핑. `knowledge`를 주면 검색된 참고 자료로 덧붙인다.

    참고 자료는 **브리핑 안**에 넣지 시스템 프롬프트에 넣지 않는다. 질의마다
    다른 문서가 붙어야 하는데 시스템 프롬프트는 질의와 무관하게 고정이기
    때문이다. 이 구분이 곧 "프롬프트에 박는 것"과 "검색해서 붙이는 것"의
    차이이며, 이 프로젝트가 재려는 것이 정확히 그 차이다.
    """
    brief = f"""실패한 검색 질의를 진단하고 치유하라.

- 실패 질의: "{query}"
- 현재 검색 결과: {n_results}건

도구로 증거를 수집해 원인을 진단한 뒤, submit_prescription으로 처방을
제출하라. 게이트가 채택할 때까지 진료는 끝나지 않는다."""

    if not knowledge:
        return brief

    return f"""{brief}

---

## 참고 자료 (지식베이스에서 검색된 문서)

아래는 이 증상과 관련될 수 있는 검색 운영 문서다. **이 질의에 대한 답이
아니라 일반 원칙**이므로, 해당하는지는 도구로 모은 증거로 직접 판단하라.

{knowledge}"""
